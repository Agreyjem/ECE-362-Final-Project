// audio.c - Beyblade sound engine for the Proton (RP2350) board.
//
// GP36 runs PWM at ~146 kHz and its duty cycle is updated 8000 times per
// second, so with the board's RC filter it works like a DAC: it plays the
// real recorded collision sounds and square-wave melodies, each with its own
// volume, from the same pin.

#include <stdlib.h>
#include "pico/stdlib.h"
#include "hardware/pwm.h"
#include "audio.h"

#define AUDIO_PIN   36
#define SAMPLE_RATE 8000    // samples per second (125 us each)

// >>> VOLUMES (0-100). Collisions are set louder than the melodies.
static volatile int melody_volume  = 12;   // 100 = as loud as the original beeps
static volatile int collide_volume = 100;

// ======================= Melodies =======================
typedef struct { uint16_t freq, ms; } note_t;   // freq 0 = rest

static const note_t START[]  = { {523,200},{0,800}, {523,200},{0,800}, {523,200},{0,800}, {1047,700} };
static const note_t WINNER[] = { {392,120},{523,120},{659,120},{784,240},{0,60},{659,120},{784,600} };
static const note_t LOSER[]  = { {392,350},{0,50}, {370,350},{0,50}, {349,350},{0,50}, {330,900} };

// ======================= Collision sounds =======================
// Six real hits from a recording (filtered to 300 Hz-3 kHz, lightly compressed
// so the ring stays loud), 8-bit, 8000 Hz. The data is at the bottom of this file.
typedef struct { const int8_t *data; uint16_t len; } hit_t;
extern const hit_t HITS[];
extern const unsigned NUM_HITS;

// ======================= Player =======================
static const note_t *volatile notes;     // melody playing (NULL = none)
static int notes_left;
static uint32_t note_left, phase, phase_inc;
static bool note_on;

static const int8_t *volatile hit;       // hit playing (NULL = none)
static int hit_pos, hit_len, hit_gain, last_hit = -1;

// Called 8000 times per second: outputs one sample
static bool audio_tick(struct repeating_timer *t) {
    (void)t;
    int s = 0;
    if (hit) {
        s = hit[hit_pos] * hit_gain / 100 * collide_volume / 100;
        if (++hit_pos >= hit_len) hit = NULL;
    } else if (notes) {
        if (note_left == 0) {
            if (notes_left == 0) { notes = NULL; goto out; }
            const note_t *n = notes++;
            notes_left--;
            note_left = n->ms * SAMPLE_RATE / 1000;
            phase_inc = (uint32_t)(((uint64_t)n->freq << 32) / SAMPLE_RATE);
            note_on = n->freq != 0;
        }
        note_left--;
        if (note_on) s = ((phase += phase_inc) & 0x80000000u) ? 127 : -127;
        s = s * melody_volume / 100;
    }
out:
    pwm_set_gpio_level(AUDIO_PIN, 512 + s * 4);        // 0-1023
    return true;
}

static void play_notes(const note_t *n, int count) {
    notes = NULL; hit = NULL;                          // stop whatever is playing
    notes_left = count; note_left = 0;
    notes = n;
}

static int clamp100(int v) { return v < 0 ? 0 : v > 100 ? 100 : v; }

// ======================= Public functions =======================
void sound_init(void) {
    gpio_set_function(AUDIO_PIN, GPIO_FUNC_PWM);
    uint slice = pwm_gpio_to_slice_num(AUDIO_PIN);
    pwm_set_wrap(slice, 1023);                         // 10-bit, 150 MHz / 1024 = 146 kHz
    pwm_set_enabled(slice, true);
    for (int l = 0; l <= 512; l += 4) {                // ramp to the silence level: no pop
        pwm_set_gpio_level(AUDIO_PIN, l);
        sleep_us(200);
    }
    srand(time_us_32());
    static struct repeating_timer timer;
    add_repeating_timer_us(-1000000 / SAMPLE_RATE, audio_tick, NULL, &timer);
}

void play_start(void)  { play_notes(START,  sizeof(START)  / sizeof(note_t)); }
void play_winner(void) { play_notes(WINNER, sizeof(WINNER) / sizeof(note_t)); }
void play_loser(void)  { play_notes(LOSER,  sizeof(LOSER)  / sizeof(note_t)); }

// Random recorded hit (never the same one twice in a row), 80-100% loudness.
// Ignored while a melody is playing, so it can't cut off the countdown or fanfare.
void play_collide(void) {
    if (notes) return;
    int h;
        
    if (last_hit < 0) {
        h = rand() % (int)NUM_HITS;                    // first hit: any of them
    } else {
        h = rand() % ((int)NUM_HITS - 1);              // pick from the other 5...
        if (h >= last_hit) h++;                        // ...by skipping over the last one
    }
    
    last_hit = h;
    hit = NULL;
    hit_pos = 0;
    hit_len = HITS[h].len;
    hit_gain = 80 + rand() % 21;
    hit = HITS[h].data;
}

bool sound_is_playing() {
    return (notes || hit); 
}
void sound_wait() { 
    while (sound_is_playing()) 
        tight_loop_contents(); 
}

void sound_set_volume(int melody, int collide) {
    melody_volume  = clamp100(melody);
    collide_volume = clamp100(collide);
}

